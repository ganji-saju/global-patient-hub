interface I18nContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string) => string;
  dir: "ltr" | "rtl";
  currentLang: LanguageOption;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    const stored = localStorage.getItem("gcl_lang") as Language | null;
    return stored && LANGUAGES.some((language) => language.code === stored) ? stored : "en";
  });

  const setLang = useCallback((newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem("gcl_lang", newLang);
  }, []);

  const currentLang = LANGUAGES.find((language) => language.code === lang) ?? LANGUAGES[0];
  const dir = currentLang.dir;

  useEffect(() => {
    const root = document.documentElement;
    const { body } = document;

    root.lang = lang;
    root.dir = dir;
    root.dataset.lang = lang;
    root.dataset.direction = dir;

    body.dir = dir;
    body.dataset.direction = dir;
  }, [dir, lang]);

  const t = useCallback(
    (key: string): string => {
      return T[key]?.[lang] ?? T[key]?.en ?? key;
    },
    [lang],
  );

  return <I18nContext.Provider value={{ lang, setLang, t, dir, currentLang }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
